package app

import (
	"fmt"

	"mycalendar/color"
)

// PrintHelp shows the manual with examples.
func PrintHelp() {
	p := func(s string) { fmt.Println(s) }

	p("")
	p(color.Yellow("============================================="))
	p(color.Yellow("        MyCalendar — справка и примеры"))
	p(color.Yellow("============================================="))

	p(color.Green("\n1. Команды из терминала (без входа в меню)"))
	p("  Даты и периоды можно указывать в любом удобном формате:")
	p("  '2026', '12.2025', '2025-12', '15-20', '01.12-15.12'.")
	p("")
	p(color.Green("  mycal add [дата]") + "        добавить запись (без даты — спросит все поля)")
	p(color.Green("  mycal view [период] [-t <тип>]") + " показать записи за период (без периода — подменю)")
	p(color.Green("  mycal type [тип]") + "          показать записи по типу (без типа — интерактивный выбор)")
	p(color.Green("  mycal delete [id|период]") + " удалить запись по ID или пачкой за период")
	p(color.Green("  mycal export [период] [-t <тип>]") + " экспорт в CSV рядом с файлом данных")
	p(color.Green("  mycal import [файл]") + "          импорт из CSV / JSON с пропуском дубликатов")
	p(color.Green("  mycal today | week | month") + "   быстрый просмотр (кратко: t | w | m)")
	p(color.Green("  mycal -c <префикс> ...") + "       выполнить команду для календаря с указанным префиксом")
	p(color.Green("  mycal -tui") + "                 запуск интерактивного полноэкранного TUI")
	p(color.Green("  mycal web [--lan] [порт]") + "   запуск веб-интерфейса (--lan открывает доступ по сети)")
	p(color.Green("  mycal service [команда]") + "    управление фоновой службой (install/status/stop/start)")
	p(color.Green("  mycal help") + "              эта справка (также -h, --help, /?)")
	p(color.Green("  mycal version") + "           версия программы (-v, --version)")
	p("")
	p("  Примеры команд:")
	p("    mycal add 15.12.2025              добавить на конкретный день")
	p("    mycal view 2026                   все записи за 2026 год")
	p("    mycal view 2026 --type \"Стрельба\" записи за 2026 с типом Стрельба")
	p("    mycal type \"Стрельба из лука\"     все записи выбранного типа")
	p("    mycal view 12.2025                за декабрь 2025 (или 2025-12)")
	p("    mycal view 15-20                  с 15 по 20 число текущего месяца")
	p("    mycal view 01.12-15.12            с 1 по 15 декабря текущего года")
	p("    mycal delete 15-20                удалить записи с 15 по 20 число")
	p("    mycal delete 20261209110005       удалить запись по ID")
	p("    mycal export 2026                 экспорт 2026 года в CSV")
	p("    mycal export 2026 -t \"Стрельба\"   экспорт записей типа Стрельба за 2026")

	p(color.Green("\n2. Ввод дат, времени и периодов"))
	p("  Дата:    ДД.ММ.ГГГГ, ДД-ММ-ГГГГ, ГГГГ-ММ-ДД; можно ДД.ММ или ДД-ММ (текущий год).")
	p("           Примеры: 15.06.2026, 5.1.2026, 2026-06-15, 15-06, 5-1.")
	p("           Некорректная дата (например 32.01.2026) переносится по календарю")
	p("           на 01.02.2026. Поведение настраивается: Настройки → Проверка даты")
	p("           (Выключена / Спрашивать / Исправлять авто / Переспрашивать).")
	p("  Время:   14:30, 1430, 14.30, 9 (= 09:00), 24 (= 00:00).")
	p("  Период:  год ('2026'), месяц ('12', '12.2025', '2025-12'),")
	p("           диапазон месяцев ('10-12'), диапазон дней месяца ('15-20'),")
	p("           диапазон дат ('01.12-15.12', '01.12.2025 – 15.12.2025').")

	p(color.Green("\n3. Горячие клавиши"))
	p("  Вместо цифр пунктов меню можно нажимать буквы — работают обе раскладки.")
	p("  В главном меню:")
	p("    a / д — добавить         v / п — просмотр        d / у — удалить")
	p("    t / с — сегодня          x / э — экспорт         i / и — импорт CSV/JSON")
	p("    s / н — настройки        u / о — отмена действия h / м — справка")
	p("    c / к — выбрать календарь  n / сз — создать календарь  q / в — выход")
	p("  При выборе повтора записи:")
	p("    d / д — каждый день      w / н — каждую неделю   m / м — каждый месяц")

	p(color.Green("\n4. Просмотр записей"))
	p("  N или ID           — подробности записи")
	p("  all / все / a       — подробности всех записей списка")
	p("  \\N или \\ID          — редактировать запись (например, '\\3')")
	p("  cN или \\cN          — дублировать запись (например, 'c3')")
	p("  mN или \\mN          — перенести запись в другой календарь (например, 'm3')")
	p("  u или г             — отменить последнее действие (Undo)")
	p("  t или т (также /t)  — интерактивный фильтр текущего списка по типам [✓]")
	p("  t <текст>           — быстрый фильтр текущего списка по типу (напр. 't стрельб')")
	p("  /текст              — поиск в текущем списке по названию или типу (напр. '/работа')")
	p("  Enter               — назад")

	p(color.Green("\n5. Редактирование"))
	p("  Enter               — оставить поле без изменений")
	p("  '-' в комментарии   — очистить комментарий, в кэше — сбросить в 0")
	p("  0                   — отмена")
	p("  Для повторяющейся записи спрашивается: одна запись или вся серия.")

	p(color.Green("\n6. Повторяющиеся записи"))
	p("  При добавлении можно повторять запись каждый день / неделю / месяц")
	p("  до указанной даты. Каждое повторение — самостоятельная запись,")
	p("  помеченная '*' и связанная с остальными в серию.")
	p("  Месячный повтор держится своего числа: с 31 января — это 28/29 февраля,")
	p("  31 марта, 30 апреля и т. д. (в коротких месяцах — последний день).")
	p("  Одна серия ограничена 5000 записями.")

	p(color.Green("\n7. Хранение, календари и надёжность"))
	p("  Данные — локальный JSON. Сохранение атомарное, с резервной копией (.bak).")
	p("  Поддерживается несколько независимых календарей (<имя>--<префикс>.json)")
	p("  с индивидуальным режимом хранения для каждого (один файл / по годам / по месяцам).")
	p("  При смене режима хранения файлы автоматически перегруппируются.")
	p("  При старте выполняется проверка целостности (Data Doctor): битые ID,")
	p("  дубли, некорректное время — с предложением автоматической починки.")
	p("  Повреждённый файл не затирается: он сохраняется как *.corrupt-<дата>,")
	p("  а работа продолжается (из .bak, если он цел).")
	p("  Записи, у которых ID не содержит даты, при разбиении по годам/месяцам")
	p("  складываются в unknown_<имя>.json — они не теряются.")

	p(color.Yellow("\n=============================================\n"))
}
