package app

import (
	"fmt"

	"mycalendar/color"
)

// PrintHelp shows the manual with examples.
func PrintHelp() {
	p := func(s string) { fmt.Println(s) }

	p("")
	p(color.Yellow("============================================="))
	p(color.Yellow("        MyCalendar — справка и примеры"))
	p(color.Yellow("============================================="))

	p(color.Green("\n1. Команды из терминала (без входа в меню)"))
	p("  Даты можно указывать неполными: '2026', '12.2025', '10-15'.")
	p("")
	p(color.Green("  mycal add [дата]") + "        добавить запись (без даты — спросит)")
	p(color.Green("  mycal view [период]") + "     показать записи за период")
	p(color.Green("  mycal delete [id|период]") + " удалить запись(и)")
	p(color.Green("  mycal export [период]") + "    экспорт в CSV рядом с файлом данных")
	p(color.Green("  mycal today | week | month") + "   (t | w | m)")
	p(color.Green("  mycal help"))
	p("")
	p("  Примеры:")
	p("    mycal add 15.12.2025")
	p("    mycal view 2026        все записи за 2026 год")
	p("    mycal view 12.2025     за декабрь 2025")
	p("    mycal view 15-20       с 15 по 20 число текущего месяца")
	p("    mycal delete 20261209110005")

	p(color.Green("\n2. Ввод дат и времени"))
	p("  Дата:  ДД-ММ-ГГГГ, ДД.ММ.ГГГГ, ГГГГ-ММ-ДД; можно ДД-ММ (текущий год).")
	p("         Некорректная дата (например 32.01.2026) переносится по календарю")
	p("         на 01.02.2026. Поведение настраивается: Настройки → Проверка даты")
	p("         (Выключена / Спрашивать / Исправлять авто / Переспрашивать).")
	p("  Время: 14:30, 1430, 14.30, 9 (= 09:00), 24 (= 00:00).")
	p("  Период: год ('2026'), месяц ('12' или '12.2025'),")
	p("          диапазон месяцев ('10-12'), диапазон дней ('01.12-15.12').")

	p(color.Green("\n3. Горячие клавиши"))
	p("  Вместо цифр можно нажимать буквы — работают обе раскладки")
	p("  (например, в 'Просмотре' 'a' или 'ф' — 'Все записи').")

	p(color.Green("\n4. Просмотр записей"))
	p("  N или ID           — подробности записи")
	p("  all / все / a       — подробности всех записей списка")
	p("  \\N или \\ID          — редактировать запись (например, '\\3')")
	p("  /текст              — отфильтровать текущий список (например, '/работа')")
	p("  Enter               — назад")

	p(color.Green("\n5. Повторяющиеся записи"))
	p("  При добавлении можно повторять запись каждый день / неделю / месяц")
	p("  до указанной даты. Каждое повторение — самостоятельная запись,")
	p("  помеченная '*' и связанная с остальными в серию.")
	p("  При правке или удалении повтора спрашивается: одна запись или вся серия.")

	p(color.Green("\n6. Хранение и надёжность"))
	p("  Данные — локальный JSON. Сохранение атомарное, с резервной копией (.bak).")
	p("  Режим хранения (Настройки): один файл / по годам / по месяцам —")
	p("  при смене режима файлы автоматически перегруппируются.")
	p("  При старте выполняется проверка целостности (Data Doctor): битые ID,")
	p("  дубли, некорректное время — с предложением автоматической починки.")
	p("  Повреждённый файл не затирается: он сохраняется как *.corrupt-<дата>,")
	p("  а работа продолжается (из .bak, если он цел).")

	p(color.Yellow("\n=============================================\n"))
}
