package app

import (
	"fmt"

	"mycalendar/color"
)

// PrintHelp displays the help manual with examples.
func PrintHelp() {
	p := func(s string) { fmt.Println(s) }

	p("")
	p(color.Yellow("============================================="))
	p(color.Yellow("        MyCalendar — Справка и примеры"))
	p(color.Yellow("============================================="))

	p(color.Green("\n1. Использование из командной строки (CLI)"))
	p("Команды выполняются без входа в главное меню. Даты можно указывать")
	p("неполными (например, '2026' или '12.2025').")
	p("")
	p(color.Green("  mycal add [дата]") + "     — быстрое добавление (без даты — интерактивно)")
	p(color.Green("  mycal view [период]") + "  — просмотр за период")
	p(color.Green("  mycal delete [id|период]"))
	p(color.Green("  mycal export [период]") + " — экспорт в CSV рядом с файлом данных")
	p(color.Green("  mycal today | week | month") + " (t | w | m)")
	p("")
	p("  Примеры:")
	p("    mycal add 15.12.2025")
	p("    mycal view 2026        — все записи за 2026 год")
	p("    mycal view 12.2025     — за декабрь 2025")
	p("    mycal view 15-20       — с 15 по 20 число текущего месяца")
	p("    mycal delete 20261209110005")

	p(color.Green("\n2. Умный ввод дат и времени"))
	p("  - Только часы: '15' — это '15:00'.")
	p("  - Период: год ('2026'), месяц ('12' / '12.2025'), диапазон ('10-15', '01.12-15.12').")

	p(color.Green("\n3. Горячие клавиши"))
	p("  - В меню вместо цифр можно нажимать буквы; работают обе раскладки.")
	p("  - Например, в 'Просмотре записей' 'a' (или 'ф') — пункт 'Все записи'.")

	p(color.Green("\n4. Режим просмотра записей"))
	p("  - Номер или ID (14 цифр) — показать подробности записи.")
	p("  - 'all' (или 'все', 'a') — развернуть подробности всех записей списка.")
	p("  - '\\N' или '\\ID' — быстрое редактирование (например, '\\3').")
	p("  - '/текст' — отфильтровать текущий список (например, '/работа').")
	p("  - При правке повтора можно изменить либо одну запись, либо всю серию.")

	p(color.Yellow("\n=============================================\n"))
}
